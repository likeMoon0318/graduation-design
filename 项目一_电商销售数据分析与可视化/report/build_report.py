def chapter8(doc):
    heading(doc, "第 8 章　结论与展望", 1)

    heading(doc, "8.1　主要结论", 2)
    para(doc, "本文完成了一套从数据生成到交互式看板的完整电商数据分析系统，"
              "在数据、方法、结论与工程四个层面都取得了可复现、可验证的成果。"
              "主要结论可以归纳为以下几点。")
    para(doc, "第一，销售结构高度集中。手机数码与家用电器两个品类贡献 69.0% 的销售额，"
              "前三个品类累计占比 82.9%。这一结构决定了库存、履约与售后资源应当"
              "优先向头部品类倾斜。")
    para(doc, "第二，大促的作用机制是“以价换量”。大促期间客单价 931.97 元，"
              "显著低于平日的 1206.55 元（p < 0.001），但订单量大幅提升；"
              "同时大促期间退货率从 9.3% 上升到 12.4%。"
              "促销评估不应只看销售额绝对值，还要同时考虑毛利率与退货成本。")
    para(doc, "第三，退货主要由商品属性决定，而不是由下单渠道决定。"
              "品类与退货的关联强度达到中等水平（Cramér's V = 0.280），"
              "服饰鞋包退货率高达 24.0%；而渠道与退货的关联不显著（p = 0.055）。"
              "退货治理的着力点应当是商品端的尺码信息、详情页描述与质量管控。")
    para(doc, "第四，用户评分是退货的有效先行指标。评分与退货率呈单调递减关系，"
              "评分 1 分订单退货率 42.1%，评分 5 分仅 6.9%，"
              "退货与未退货订单的评分差异显著（Mann-Whitney U 检验，p < 0.001）。")
    para(doc, "第五，客户分层清晰且可操作。KMeans 把客户划分为核心价值、稳定活跃、"
              "一般维持与流失预警四群，四群在 R、F、M 三个维度上形成明显的层次结构，"
              "可以分别对应专属维护、交叉销售、满减刺激与低成本召回四类运营动作。")
    para(doc, "第六，订单金额可解释性良好。岭回归在测试集上的 R² 达到 0.797，"
              "单价与订单金额的 Spearman 相关系数为 0.913，"
              "说明订单金额主要由商品品类与单价结构决定。")
    para(doc, "第七，退货风险可以被提前识别。类别加权逻辑回归的 AUC 为 0.759、"
              "召回率 68.79%，可以作为售后资源预置的辅助工具。")

    heading(doc, "8.2　不足与改进方向", 2)
    para(doc, "第一，数据来源于仿真而非真实业务系统。虽然仿真模型参考了真实的促销节奏、"
              "消费结构与人机交互规律，但仍无法完全复现真实数据的噪声形态与长尾异常。"
              "后续可在获得授权的前提下接入脱敏的真实订单数据，"
              "用同一套流程做对比验证。")
    para(doc, "第二，模型层面仍有提升空间。订单金额回归使用的是线性模型，"
              "对品类与地区之间的交互效应刻画不足，后续可尝试梯度提升树并做特征交互；"
              "退货预测目前是静态模型，可以考虑引入客户历史行为序列特征，"
              "并使用按时间切分的验证集以更贴近线上场景。")
    para(doc, "第三，客户分群使用的是传统 KMeans，需要预先指定簇数且对初始中心敏感。"
              "后续可以尝试 DBSCAN、高斯混合模型或基于深度嵌入的聚类方法，"
              "并引入时间维度构建客户状态的动态迁移分析。")
    para(doc, "第四，看板目前是桌面端单机应用，数据量进一步增大时需要改用"
              "数据库或列式存储；交互形式上也可以扩展为 Web 端看板，"
              "以便多人协作与移动端访问。")
    para(doc, "第五，分析结论目前以描述与推断为主，尚未进行因果推断。"
              "例如大促对平时销售的“透支效应”需要借助双重差分或合成控制方法"
              "才能给出更严格的判断，这是后续值得深入的方向。")


